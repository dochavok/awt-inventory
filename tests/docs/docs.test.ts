// The user guide and maintainer guide (section 19: DOC-2, DOC-4 to DOC-6).
// DOC-1 (help inside the app, offline too) is in tests/browser/phone.spec.ts.

import { existsSync, readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { expect } from "vitest";
import { fixtureCharacters } from "../support/fixtures";
import { rule } from "../support/rule";
import { runScript } from "../support/run-script";

const ROOT = new URL("../../", import.meta.url);
const DOCS = new URL("../../docs/", import.meta.url);

function userPages(): { file: string; title: string; text: string }[] {
  expect(existsSync(DOCS), "docs/ exists").toBe(true);
  return readdirSync(fileURLToPath(DOCS))
    .filter((f) => f.endsWith(".md") && !["maintainer.md", "restore-runbook.md"].includes(f))
    .map((file) => {
      const text = readFileSync(new URL(file, DOCS), "utf8");
      return { file, title: /^# (.+)$/m.exec(text)?.[1]?.trim() ?? "", text };
    });
}

const titles = () => userPages().map((p) => p.title);
const page = (title: string) => userPages().find((p) => p.title === title);

rule({ req: ["DOC-2"], m: "M3" }, "the guide has a page for each topic built by M3", () => {
  expect(titles(), "the guide's page titles").toEqual(
    expect.arrayContaining([
      "Getting started",
      "Characters and titles",
      "The inventory",
      "Skills",
      "History",
      "Search and export",
      "Terms of use",
      "Privacy",
      "Troubleshooting",
      "Glossary",
    ]),
  );
});

rule({ req: ["DOC-2", "EX-5"], m: "M3" }, "the search and export page describes the JSON format", () => {
  expect(page("Search and export")?.text, "the Search and export page").toMatch(/formatVersion/);
});

rule({ req: ["DOC-2"], m: "M4" }, "from M4 the guide has an Equipping and totals page", () => {
  expect(titles(), "the guide's page titles").toContain("Equipping and totals");
});

rule({ req: ["DOC-2"], m: "M5" }, "from M5 the guide has a Permissions and rarity page", () => {
  expect(titles(), "the guide's page titles").toContain("Permissions and rarity");
});

rule({ req: ["DOC-2"], m: "M3" }, "the glossary page explains every term in the requirements' glossary", () => {
  const requirements = readFileSync(new URL("inventory-requirements.md", ROOT), "utf8");
  const section = requirements.split("## 2. Glossary")[1]!.split("\n## ")[0]!;
  const terms = [...section.matchAll(/^\| \*\*(.+?)\*\*/gm)].flatMap((m) => m[1]!.split(/\*\*, \*\*/));
  expect(terms.length, "terms in the requirements' glossary").toBeGreaterThan(30);
  const glossary = page("Glossary")?.text ?? "";
  for (const term of terms) expect(glossary, `the glossary page explaining ${term}`).toContain(term);
});

rule({ req: ["DOC-2"], m: "M4" }, "the troubleshooting page covers every block the app can show", () => {
  const blocks = [
    "wrong slot",
    "slot full",
    "hands not free",
    "two shields",
    "not arcane",
    "arcane full",
    "over limit",
    "cannot equip",
    "already equipped",
  ];
  const text = (page("Troubleshooting")?.text ?? "").toLowerCase().replaceAll("-", " ");
  for (const block of blocks) expect(text, `the troubleshooting page covering "${block}"`).toContain(block);
});

rule({ req: ["DOC-2"], m: "M5" }, "the troubleshooting page covers the rarity blocks and permission warnings", () => {
  const items = ["rarity limit", "rarity level", "weapon use", "ranged weapon use", "armor use", "dual wielding"];
  const text = (page("Troubleshooting")?.text ?? "").toLowerCase().replaceAll("-", " ");
  for (const item of items) expect(text, `the troubleshooting page covering "${item}"`).toContain(item);
});

rule({ req: ["DOC-2", "SK-3"], m: "M3" }, "the troubleshooting page covers the skill warnings", () => {
  const warnings = ["missing prerequisite", "another class", "entry level", "already"];
  const text = (page("Troubleshooting")?.text ?? "").toLowerCase();
  for (const warning of warnings) expect(text, `the troubleshooting page covering "${warning}"`).toContain(warning);
});

rule(
  { req: ["DOC-4"], m: "M3" },
  "the guide's examples are generated by the app, and the check that they match passes",
  () => {
    const script = new URL("scripts/generate-docs.ts", ROOT);
    expect(existsSync(script), "scripts/generate-docs.ts exists").toBe(true);
    const { exitCode, output } = runScript("scripts/generate-docs.ts", "--check");
    expect(exitCode, `generate-docs --check (${output.trim()})`).toBe(0);
  },
);

rule({ req: ["DOC-4"], m: "M3" }, "the docs' sample character is kept with the docs and isn't a test fixture", () => {
  const sampleDir = new URL("docs/sample/", ROOT);
  expect(existsSync(sampleDir), "docs/sample/ exists").toBe(true);
  const sample = readdirSync(fileURLToPath(sampleDir))
    .map((f) => readFileSync(new URL(f, sampleDir), "utf8"))
    .join("\n");
  for (const name of Object.values(fixtureCharacters()).map((c) => c.character.name)) {
    expect(sample, `the docs sample using the fixture character ${name}`).not.toMatch(new RegExp(`\\b${name}\\b`));
  }
});

rule({ req: ["DOC-5"], m: "M3" }, "the maintainer guide lists every recurring task", () => {
  expect(existsSync(new URL("maintainer.md", DOCS)), "docs/maintainer.md exists").toBe(true);
  const guide = readFileSync(new URL("maintainer.md", DOCS), "utf8").toLowerCase();
  for (const task of [
    "reference data",
    "skill list",
    "invite list",
    "dm's answer",
    "dependabot",
    "error reports",
    "backups",
    "restor",
    "secrets",
    "reports",
    "updating the guide",
  ]) {
    expect(guide, `the maintainer guide covering "${task}"`).toContain(task);
  }
});

rule({ req: ["DOC-6"], m: "M3" }, "every help page records when it was last reviewed", () => {
  const pages = userPages();
  expect(pages.length, "help pages").toBeGreaterThan(0);
  for (const p of pages) expect(p.text, `${p.file}'s review date`).toMatch(/^reviewed: \d{4}-\d{2}-\d{2}$/m);
});
